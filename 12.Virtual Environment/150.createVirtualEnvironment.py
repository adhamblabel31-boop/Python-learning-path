# show python package
#? pip list

# create directory which name envs and go to it
#? mkdir envs && cd envs

# show all parameter of python
#? python --help

# create a Virtual Environment named ai
#? python -m venv ai

# create a Virtual Environment named pen
#? python -m venv pen

# activate ai Virtual Environment
#? source ai/scripts/activate --> windows
#? source ai/bin/activate     --> linux

# activate pen Virtual Environment
#? source pen/scripts/activate --> windows
#? source pen/bin/activate     --> linux

# upgrade version of pip
#? python -m pip install --upgrade pip

# deactive Virtual Environment
#? deactivate

# show python working path
#? which python
